'use strict';
/* Unified Leave Approval Inbox. Existing leave endpoints remain authoritative.
   No signatures or DTR punches are generated by this view. */
(() => {
 const FILTERS=[
  ['ACTION','Needs my review','action'],['PENDING','Pending','pending'],
  ['RECOMMENDATION','For recommendation','recommendation'],
  ['SCHOOL_REVIEW','School review','schoolReview'],
  ['EXTERNAL','Awaiting official approval','external'],
  ['APPROVED','Approved','approved'],
  ['DISAPPROVED','Disapproved','disapproved'],
  ['ALL','All requests','total']
 ];
 let filter='ACTION',query='',offset=0,badge=null,badgeButton=null,badgeApi=null;
 const safeText=value=>String(value??'');
 const date=value=>safeText(value).slice(0,10)||'—';
 const make=(tag,cls,text)=>{
  const el=document.createElement(tag);
  if(cls)el.className=cls;
  if(text!==undefined)el.textContent=safeText(text);
  return el;
 };
 const notify=(box,text,error=false)=>{box.textContent=text;box.classList.toggle('is-error',error);};
 const createInput=(label,type,name,required=true,extra={})=>{
  const wrap=make('label','leave-inbox-field');
  wrap.append(make('span',null,label));
  const el=make(type==='textarea'?'textarea':'input');
  if(type!=='textarea')el.type=type;
  el.name=name;el.required=required;
  if(extra.maxLength)el.maxLength=extra.maxLength;
  if(extra.step)el.step=extra.step;
  if(extra.min)el.min=extra.min;
  if(extra.accept)el.accept=extra.accept;
  if(extra.placeholder)el.placeholder=extra.placeholder;
  wrap.append(el);
  return wrap;
 };
 const makeButton=(title,cls,fn)=>{
  const b=make('button',cls,title);b.type='button';b.addEventListener('click',fn);return b;
 };
 function reviewForm(request,kind,ctx){
  const form=make('form','leave-inbox-review-form');
  const title=kind==='HEAD'?'Department recommendation':'School review';
  form.append(make('h4',null,title));
  const note=createInput('Review note (required for a negative recommendation)','textarea','note',false,{maxLength:1000});
  form.append(note);
  const choices=make('div','leave-inbox-form-actions');
  const submit=decision=>{
   const value=note.querySelector('textarea').value.trim();
   if(decision==='REJECT'&&value.length<3){notify(ctx.message,'Explain the reason for recommending disapproval.',true);return;}
   const path=kind==='HEAD'?'recommend':'admin-review';
   void ctx.action('Recording '+title.toLowerCase(),()=>ctx.call('/requests/'+request.requestId+'/'+path,'POST',{decision,note:value}));
  };
  choices.append(
   makeButton(kind==='HEAD'?'Recommend approval':'Forward for official decision','leave-primary',()=>submit('FORWARD')),
   makeButton('Recommend disapproval','leave-btn',()=>submit('REJECT'))
  );
  form.append(choices);
  form.append(make('p','leave-help','A recommendation is not a final approval or disapproval. The authorized official must issue the final decision.'));
  return form;
 }
 function officialForm(request,ctx){
  const form=make('form','leave-inbox-review-form');
  form.append(make('h4',null,'Record authorized official decision'));
  form.append(make('p','leave-help',
   'This records a decision already signed by the authorized DepEd official. It does not digitally approve, sign, or grant approval authority.'));
  const selectLabel=make('label','leave-inbox-field');
  selectLabel.append(make('span',null,'Official decision'));
  const select=make('select');select.name='decision';
  [['APPROVE','Officially approved'],['REJECT','Officially disapproved']].forEach(([value,label])=>{
   const o=make('option',null,label);o.value=value;select.append(o);
  });
  selectLabel.append(select);form.append(selectLabel);
  form.append(createInput('Official approval / decision reference','text','approvalReference',true,{maxLength:120}));
  form.append(createInput('Name of authorized official','text','approverName',true,{maxLength:120}));
  form.append(createInput('Official position','text','approverPosition',true,{maxLength:120}));
  form.append(createInput('Date of official decision','date','approvedOn'));
  const working=createInput('HR-certified working days (for approved leave)','number','certifiedWorkingDays',true,{step:'0.001',min:'0.001'});
  form.append(working);
  const proof=createInput('Signed official decision (PDF, JPG, PNG; 4 MB max)','file','file',false,{accept:'.pdf,.jpg,.jpeg,.png,application/pdf,image/jpeg,image/png'});
  form.append(proof);
  form.append(createInput('Notes (optional)','textarea','note',false,{maxLength:1000}));
  const sync=()=>{working.querySelector('input').required=select.value==='APPROVE';};
  select.addEventListener('change',sync);sync();
  const submit=make('button','leave-primary','Verify and record official decision');
  submit.type='submit';form.append(submit);
  form.addEventListener('submit',event=>{
   event.preventDefault();
   if(!form.reportValidity())return;
   const data=new FormData(form);
   const officialDecision=safeText(data.get('decision'));
   const days=Number(data.get('certifiedWorkingDays'));
   const file=data.get('file');
   if(officialDecision==='APPROVE'&&(!(file instanceof File)||!file.size)){
    notify(ctx.message,'Attach the signed official approval before finalizing.',true);
    return;
   }
   void ctx.action('Recording official decision',async()=>{
    if(file instanceof File&&file.size)
     await ctx.upload('/requests/'+request.requestId+'/documents',file,'APPROVAL');
    return ctx.call('/requests/'+request.requestId+'/external-decision','POST',{
     decision:officialDecision,approvalReference:safeText(data.get('approvalReference')).trim(),
     approverName:safeText(data.get('approverName')).trim(),
     approverPosition:safeText(data.get('approverPosition')).trim(),
     approvedOn:safeText(data.get('approvedOn')),certifiedWorkingDays:days,
     note:safeText(data.get('note')).trim()
    });
   });
  });
  return form;
 }
 function card(record,ctx){
  const article=make('article','leave-inbox-card');
  const head=make('div','leave-card-top');
  const info=make('div');
  info.append(make('strong',null,record.staffName||'Staff'));
  info.append(make('small','leave-inbox-department',
   (record.departmentName||'School')+' · '+(record.own?'My request':'Staff application')));
  const status=make('span','leave-status',record.statusLabel||'Under review');
  status.dataset.leaveStatus=record.status;
  head.append(info,status);article.append(head);
  article.append(make('p','leave-inbox-dates',
   date(record.startDate)+' – '+date(record.endDate)+' · '+(record.leaveType?record.leaveType.replaceAll('_',' ').toLowerCase():'Leave application')));
  const track=make('div','leave-inbox-timeline');
  const timeline=[
   ['Application filed',Boolean(record.submittedAt)],
   ['Department recommendation',Boolean(record.headReviewedAt)],
   ['School review',Boolean(record.schoolReviewedAt)],
   ['Official decision',Boolean(record.officialDecisionAt)]
  ];
  timeline.forEach(([label,done],i)=>{
   const dot=make('span',done?'leave-inbox-stage is-done':'leave-inbox-stage',label);
   dot.title=done?'Recorded':'Awaiting this step or step not applicable';
   if(record.status==='REJECTED'&&i===3)dot.classList.add('is-done');
   track.append(dot);
  });
  article.append(track);
  const actions=make('div','leave-actions');
  actions.append(makeButton('CSC Form No. 6','leave-btn',()=>{
   window.open('/leave-form6.html?requestId='+encodeURIComponent(record.requestId),'_blank');
  }));
  actions.append(makeButton(record.own?'My request details':'Open Leave Requests','leave-btn',ctx.openRequests));
  article.append(actions);
  if(record.own && record.status!=='APPROVED' && record.status!=='REJECTED'){
   article.append(make('p','leave-help','Your request is awaiting the next authorized review. You cannot approve your own leave.'));
  }
  if(record.actions?.recommend||record.actions?.schoolReview||record.actions?.recordOfficialDecision){
   const details=make('details','leave-approval leave-inbox-action');
   const summary=make('summary',null,record.actions.recommend?'Review department recommendation':
    record.actions.schoolReview?'Review school forwarding':'Verify official decision');
   details.append(summary);
   if(record.actions.recommend)details.append(reviewForm(record,'HEAD',ctx));
   else if(record.actions.schoolReview)details.append(reviewForm(record,'ADMIN',ctx));
   else details.append(officialForm(record,ctx));
   article.append(details);
  }else if(record.status==='PENDING_EXTERNAL' && !record.own){
   article.append(make('p','leave-help','Awaiting an officially signed decision. No final approval has been recorded.'));
  }
  return article;
 }
 async function render(ctx){
  if(!ctx?.body||!['DEPARTMENT_HEAD','SCHOOL_ADMIN'].includes(ctx.user?.role))return;
  const parent=ctx.body;
  parent.replaceChildren();
  const heading=make('div','leave-inbox-heading');
  heading.append(make('h3',null,'Leave Approval Inbox'));
  heading.append(makeButton('Refresh','leave-btn',()=>{void render(ctx).catch(e=>notify(ctx.message,e.message,true));}));
  parent.append(heading);
  parent.append(make('p','leave-help',
   'Review recommendations, track outstanding official decisions and monitor completed requests. Final decisions require documentary verification by an authorized officer.'));
  const summary=make('div','leave-inbox-filters');
  summary.setAttribute('role','group');
  summary.setAttribute('aria-label','Filter leave approval requests');
  const status=make('div','leave-inbox-count-note','Loading application statuses…');
  FILTERS.forEach(([value,label,key])=>{
   const b=make('button',filter===value?'leave-inbox-filter is-current':'leave-inbox-filter');
   b.type='button';b.dataset.filter=value;b.setAttribute('aria-pressed',String(filter===value));
   b.append(make('span',null,label),make('strong','leave-inbox-filter-count','—'));
   b.addEventListener('click',()=>{
    filter=value;offset=0;
    void render(ctx).catch(e=>notify(ctx.message,e.message,true));
   });
   b.dataset.count=key;summary.append(b);
  });
  parent.append(summary);
  const search=make('form','leave-inbox-search');
  const input=make('input');input.type='search';input.name='query';input.value=query;
  input.placeholder='Search employee or request ID';input.setAttribute('aria-label','Search leave requests');
  const submit=make('button','leave-btn','Search');submit.type='submit';
  search.append(input,submit);
  search.addEventListener('submit',event=>{
   event.preventDefault();query=input.value.trim().slice(0,100);offset=0;
   void render(ctx).catch(e=>notify(ctx.message,e.message,true));
  });
  parent.append(search);
  parent.append(status);
  const list=make('div','leave-inbox-list');parent.append(list);
  const paging=make('div','leave-inbox-pagination');parent.append(paging);
  try{
   const data=await ctx.call('/inbox?filter='+encodeURIComponent(filter)+
    '&q='+encodeURIComponent(query)+'&limit=25&offset='+offset);
   const counts=data.counts||{};
   summary.querySelectorAll('[data-filter]').forEach(btn=>{
    btn.querySelector('strong').textContent=safeText(counts[btn.dataset.count]||0);
   });
   status.textContent=safeText(counts.action||0)+' request(s) need your attention · '+
    safeText(counts.pending||0)+' pending in your authorized scope.';
   list.replaceChildren();
   const records=data.requests||[];
   if(!records.length)list.append(make('p','leave-empty',
    filter==='ACTION'?'No leave applications currently require your review.':
     'No leave applications match this filter.'));
   else records.forEach(r=>list.append(card(r,ctx)));
   paging.replaceChildren();
   if(offset>0)paging.append(makeButton('Previous','leave-btn',()=>{
    offset=Math.max(0,offset-25);void render(ctx).catch(e=>notify(ctx.message,e.message,true));
   }));
   if(data.nextOffset!=null)paging.append(makeButton('Next','leave-btn',()=>{
    offset=data.nextOffset;void render(ctx).catch(e=>notify(ctx.message,e.message,true));
   }));
  }catch(e){
   status.textContent='Could not load the approval inbox.';
   list.replaceChildren(make('p','leave-empty',e.message));
   throw e;
  }
 }
 async function refreshBadge(){
  if(!badge||!badgeApi||document.hidden)return;
  try{
   const r=await badgeApi('/inbox?countsOnly=1');
   const n=Number(r.counts?.action)||0;
   badge.hidden=n===0;
   badge.textContent=n>99?'99+':String(n);
   if(badgeButton)badgeButton.title=n?n+' leave request(s) awaiting review':'Leave requests and approvals';
  }catch{badge.hidden=true;}
 }
 function attachNav(button,user,call){
  if(!button||!['DEPARTMENT_HEAD','SCHOOL_ADMIN'].includes(user?.role))return;
  badgeButton=button;badgeApi=call;
  badge=make('span','leave-inbox-nav-badge','0');
  badge.hidden=true;badge.setAttribute('aria-label','Pending leave reviews');
  button.append(badge);
  void refreshBadge();
  document.addEventListener('attendigo:requests-changed',()=>{void refreshBadge();});
  window.setInterval(()=>{void refreshBadge();},75000);
 }
 window.AttendigoLeaveInbox={render,attachNav,refreshBadge};
})();
