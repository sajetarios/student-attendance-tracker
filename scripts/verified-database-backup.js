'use strict';
// Encrypted pg_dump + actual restore verifier. No automatic fallback to old Render
// databases and no plaintext backup retention. Use a private offsite signed PUT.
require('dotenv').config();
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const crypto=require('node:crypto');
const {spawn}=require('node:child_process');
const {pipeline}=require('node:stream/promises');
const {createReadStream,createWriteStream}=require('node:fs');
const HEADER=Buffer.from('ATTENDIGO-BACKUP-1\n');
async function command(bin,args,env){
 await new Promise((resolve,reject)=>{
  const child=spawn(bin,args,{env,stdio:['ignore','ignore','pipe']});
  let stderr='';
  child.stderr.on('data',buf=>{stderr+=buf.toString().slice(0,1000);});
  child.on('error',()=>reject(Error(bin+' is unavailable. Install a matching PostgreSQL client.')));
  child.on('exit',code=>{
   if(code===0)return resolve();
   const safeLocalCi=process.env.CI==='true'&&['localhost','127.0.0.1'].includes(env.PGHOST);
   if(safeLocalCi&&bin==='pg_restore')
    console.error('[Restore CI diagnostic] '+stderr.replaceAll(env.PGPASSWORD||'__no_password__','[redacted]').slice(-1200));
   return reject(Error(bin+' failed with exit code '+code+' (details withheld to protect connection credentials)'));
  });
 });
}
function parseDb(url){
 if(!url)throw Error('Backup requires an explicit primary database URL.');
 const u=new URL(url);
 if(!['postgres:','postgresql:'].includes(u.protocol))throw Error('PostgreSQL URL required.');
 if(!u.hostname||!u.pathname.slice(1))throw Error('Incomplete PostgreSQL target.');
 return u;
}
function postgresEnv(u,overrides={}){
 const host=u.hostname,local=['127.0.0.1','localhost','::1'].includes(host);
 return {...process.env,PGHOST:host,PGPORT:u.port||'5432',
  PGUSER:decodeURIComponent(u.username),PGPASSWORD:decodeURIComponent(u.password),
  PGDATABASE:decodeURIComponent(u.pathname.slice(1)),PGSSLMODE:local?'disable':'verify-full',
  ...overrides};
}
async function primaryEnvironment(temp){
 const mode=process.env.ATTENDIGO_PRIMARY_DATABASE||'render';
 if(!['supabase','render'].includes(mode))throw Error('Unknown primary database provider.');
 const url=mode==='supabase'?process.env.SUPABASE_DATABASE_URL:process.env.DATABASE_URL;
 const parsed=parseDb(url);
 if(mode==='supabase'){
  const {inspectTarget,downloadOfficialRootCa}=require('./supabase-connection-preflight');
  if(inspectTarget(url).status!=='configured')throw Error('Unapproved Supabase backup target.');
  const ca=await downloadOfficialRootCa();
  const cert=path.join(temp,'trusted-ca.pem');
  await fs.writeFile(cert,ca,{mode:0o600,flag:'wx'});
  return postgresEnv(parsed,{PGSSLROOTCERT:cert});
 }
 if(!['127.0.0.1','localhost','::1'].includes(parsed.hostname)&&!process.env.PGSSLROOTCERT)
  throw Error('A trusted PGSSLROOTCERT is required to back up a remote Render database.');
 return postgresEnv(parsed,process.env.PGSSLROOTCERT?{PGSSLROOTCERT:process.env.PGSSLROOTCERT}:{});
}
function secretKey(){
 const value=String(process.env.ATTENDIGO_BACKUP_KEY_BASE64||'');
 const key=Buffer.from(value,'base64');
 if(!value||key.length!==32)throw Error('ATTENDIGO_BACKUP_KEY_BASE64 must be 32 securely generated bytes in base64.');
 return key;
}
async function encryptArchive(plain,encrypted,key){
 const iv=crypto.randomBytes(12),cipher=crypto.createCipheriv('aes-256-gcm',key,iv);
 const output=await fs.open(encrypted,'wx',0o600);
 try{await output.write(Buffer.concat([HEADER,iv]));}
 finally{await output.close();}
 await pipeline(createReadStream(plain),cipher,createWriteStream(encrypted,{flags:'a',mode:0o600}));
 await fs.appendFile(encrypted,cipher.getAuthTag());
}
async function decryptArchive(encrypted,plain,key){
 const file=await fs.open(encrypted,'r');
 let stat,head,iv,tag;
 try{
  stat=await file.stat();
  if(stat.size<HEADER.length+12+16+1)throw Error('Encrypted backup is truncated.');
  head=Buffer.alloc(HEADER.length);iv=Buffer.alloc(12);tag=Buffer.alloc(16);
  await file.read(head,0,head.length,0);
  await file.read(iv,0,12,head.length);
  await file.read(tag,0,16,stat.size-16);
 }finally{await file.close();}
 if(!crypto.timingSafeEqual(head,HEADER))throw Error('Invalid backup file header.');
 const decipher=crypto.createDecipheriv('aes-256-gcm',key,iv);
 decipher.setAuthTag(tag);
 await pipeline(createReadStream(encrypted,{start:HEADER.length+12,end:stat.size-17}),
  decipher,createWriteStream(plain,{mode:0o600,flags:'wx'}));
}
async function main(){
 const mode=process.argv[2];
 if(!['backup','restore-test'].includes(mode))throw Error('Usage: node scripts/verified-database-backup.js backup|restore-test [path]');
 const key=secretKey();
 const temp=await fs.mkdtemp(path.join(os.tmpdir(),'attendigo-archive-'));
 try{
  await fs.chmod(temp,0o700);
  const archive=path.join(temp,'database.dump');
  if(mode==='backup'){
   const env=await primaryEnvironment(temp);
   await command('pg_dump',['--format=custom','--no-owner','--no-acl','--file='+archive],env);
   await command('pg_restore',['--list',archive],env);
   const destination=process.argv[3]||path.join(temp,'archive.attbk');
   const remote=process.env.ATTENDIGO_BACKUP_SIGNED_PUT_URL;
   if(!remote&&process.env.ATTENDIGO_PRIMARY_DATABASE==='supabase')
    throw Error('Production backup requires ATTENDIGO_BACKUP_SIGNED_PUT_URL for independent offsite storage.');
   await encryptArchive(archive,destination,key);
   const encryptedSize=(await fs.stat(destination)).size;
   if(remote){
    const u=new URL(remote);
    if(u.protocol!=='https:')throw Error('Offsite backup URL must use HTTPS.');
    const response=await fetch(u.toString(),{method:'PUT',body:await fs.readFile(destination),
      headers:{'Content-Type':'application/octet-stream'},signal:AbortSignal.timeout(120000)});
    if(!response.ok)throw Error('Encrypted offsite upload failed; status '+response.status);
   }
   console.log(JSON.stringify({status:remote?'OFFSITE_UPLOADED':'LOCAL_ENCRYPTED_TEST_ONLY',bytes:encryptedSize,
    restoreTestRequired:true,backupFormat:'aes-256-gcm:pg_dump_custom'}));
  }else{
   const encrypted=process.argv[3],target=process.env.ATTENDIGO_RESTORE_TEST_DATABASE_URL;
   if(!encrypted||!target)throw Error('Encrypted file and ATTENDIGO_RESTORE_TEST_DATABASE_URL are required.');
   const u=parseDb(target);
   if(!/_restore_test$/.test(decodeURIComponent(u.pathname.slice(1))))
    throw Error('Refusing to restore outside a dedicated *_restore_test database.');
   await decryptArchive(encrypted,archive,key);
   const env=postgresEnv(u);
   await command('pg_restore',['--no-owner','--no-acl','--exit-on-error','--dbname='+u.pathname.slice(1),archive],env);
   console.log(JSON.stringify({status:'RESTORE_TEST_PASSED',target:'dedicated restore test database'}));
  }
 }finally{
  await fs.rm(temp,{recursive:true,force:true});
 }
}
if(require.main===module)main().catch(err=>{
 console.error('[Backup] '+err.message);
 process.exitCode=1;
});
module.exports={postgresEnv,parseDb,encryptArchive,decryptArchive};
