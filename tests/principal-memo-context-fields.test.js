'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
test('directive selector hides, disables and resets unrelated time/date fields',()=>{
 const source=fs.readFileSync('public/principal-dashboard.js','utf8');
 const body=source.slice(source.indexOf(' function syncPrincipalMemoOptions(){'),source.indexOf(' async function publishPrincipalMemo(){'));
 const fields=Object.fromEntries(['category','audience','effectiveDate','endDate','document','originalMinutes','adjustedMinutes','dismissalTime','dtrAmIn','dtrAmOut','dtrPmIn','dtrPmOut'].map(n=>[n,{value:'',required:false,disabled:false}]));
 const staff={disabled:false};
 fields.audience.querySelector=()=>staff;
 const nodes=Object.fromEntries(['principalMemoApplyDtr','principalShortenedClass','principalMemoDateFields','principalShortenedFields','principalDismissalFields','principalMemoDtrFields'].map(n=>[n,{hidden:false}]));
 nodes.principalMemoForm={elements:{namedItem:n=>fields[n]}};
 nodes.principalMemoDtrFields.querySelectorAll=()=>['dtrAmIn','dtrAmOut','dtrPmIn','dtrPmOut'].map(n=>fields[n]);
 const context=vm.createContext({$:id=>nodes[id]});
 vm.runInContext(body,context);
 const sync=()=>vm.runInContext('syncPrincipalMemoOptions()',context);
 fields.category.value='TEMPORARY_DTR';sync();
 assert.equal(nodes.principalMemoDtrFields.hidden,false);assert.equal(fields.dtrAmIn.required,true);
 fields.dtrAmIn.value='07:30';fields.effectiveDate.value='2026-12-01';
 fields.category.value='GENERAL';sync();
 assert.equal(nodes.principalMemoDateFields.hidden,true);assert.equal(nodes.principalMemoDtrFields.hidden,true);
 assert.equal(fields.dtrAmIn.value,'');assert.equal(fields.dtrAmIn.disabled,true);assert.equal(fields.effectiveDate.value,'');
 assert.equal(fields.document.required,false);
 fields.category.value='EARLY_DISMISSAL';sync();
 assert.equal(nodes.principalDismissalFields.hidden,false);assert.equal(fields.dismissalTime.required,true);
 assert.equal(nodes.principalMemoDtrFields.hidden,true);assert.equal(fields.audience.value,'ALL_USERS');
 fields.dismissalTime.value='15:00';fields.category.value='SHORTENED_PERIODS';sync();
 assert.equal(nodes.principalDismissalFields.hidden,true);assert.equal(fields.dismissalTime.value,'');
 assert.equal(nodes.principalShortenedFields.hidden,false);assert.equal(fields.originalMinutes.required,true);
 fields.category.value='SCHOOL_ADVISORY';sync();
 assert.equal(nodes.principalShortenedFields.hidden,true);assert.equal(nodes.principalMemoDateFields.hidden,true);
});
